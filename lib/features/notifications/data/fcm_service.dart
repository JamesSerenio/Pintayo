enum PushAvailability { disabled, unconfigured, ready }

abstract interface class FcmGateway {
  PushAvailability get availability;
  Future<void> initialize();
  Stream<String> get registrations;
  Stream<String> get invalidations;
  Stream<RemoteMessage> get foregroundMessages;
  Stream<RemoteMessage> get openedMessages;
  Future<RemoteMessage?> initialMessage();
  Future<bool> requestPermission();
  Future<bool> hasPermission();
  Future<void> register();
  Future<void> unregister();
}

/// Background OS notifications are displayed by FCM. This entry point never
/// displays a second alert, routes a screen, or changes chat receipts.
@pragma('vm:entry-point')
Future<void> pintayoMessagingBackgroundHandler(RemoteMessage message) async {
  try {
    if (Firebase.apps.isEmpty) await Firebase.initializeApp();
  } catch (_) {
    /* Missing native configuration cannot break durable chat. */
  }
}

class FcmService implements FcmGateway {
  final AppConfig config;
  Future<void>? _initialization;
  @override
  PushAvailability availability = PushAvailability.disabled;
  FcmService(this.config);
  FirebaseMessaging get _messaging => FirebaseMessaging.instance;

  @override
  Future<void> initialize() => _initialization ??= _initialize();
  Future<void> _initialize() async {
    if (!config.pushEnabled) return;
    availability = PushAvailability.unconfigured;
    try {
      // Android/iOS use genuine platform files generated by Firebase/FlutterFire.
      // Project metadata alone is deliberately insufficient for initialization.
      final app = Firebase.apps.isEmpty
          ? await Firebase.initializeApp()
          : Firebase.app();
      if ((config.firebaseProjectId.isNotEmpty &&
              app.options.projectId != config.firebaseProjectId) ||
          (config.firebaseMessagingSenderId.isNotEmpty &&
              app.options.messagingSenderId !=
                  config.firebaseMessagingSenderId)) {
        return;
      }
      FirebaseMessaging.onBackgroundMessage(pintayoMessagingBackgroundHandler);
      await _messaging.setForegroundNotificationPresentationOptions(
        alert: false,
        badge: false,
        sound: false,
      );
      if (defaultTargetPlatform == TargetPlatform.android) {
        await const MethodChannel(
          'pintayo/notifications',
        ).invokeMethod<void>('ensureChannel');
      }
      availability = PushAvailability.ready;
    } catch (_) {
      availability = PushAvailability.unconfigured;
    }
  }

  @override
  Stream<String> get registrations => _messaging.onRegistered;
  @override
  Stream<String> get invalidations => _messaging.onUnregistered;
  @override
  Stream<RemoteMessage> get foregroundMessages => FirebaseMessaging.onMessage;
  @override
  Stream<RemoteMessage> get openedMessages =>
      FirebaseMessaging.onMessageOpenedApp;
  @override
  Future<RemoteMessage?> initialMessage() => _messaging.getInitialMessage();
  bool _allowed(NotificationSettings settings) =>
      settings.authorizationStatus == AuthorizationStatus.authorized ||
      settings.authorizationStatus == AuthorizationStatus.provisional;
  @override
  Future<bool> hasPermission() async =>
      _allowed(await _messaging.getNotificationSettings());
  @override
  Future<bool> requestPermission() async {
    if (!_allowed(await _messaging.requestPermission())) return false;
    if (defaultTargetPlatform == TargetPlatform.iOS &&
        await _messaging.getAPNSToken() == null) {
      return false;
    }
    return true;
  }

  @override
  Future<void> register() => _messaging.register();
  @override
  Future<void> unregister() => _messaging.unregister();
}

final fcmServiceProvider = Provider<FcmGateway>(
  (ref) => FcmService(ref.watch(configProvider)),
);
